<?php

declare(strict_types=1);

namespace Nowo\BlogKitBundle\Tests\Integration;

use Doctrine\ORM\Mapping\ClassMetadata;
use Doctrine\ORM\Mapping\DefaultNamingStrategy;
use Doctrine\ORM\Mapping\Driver\AttributeDriver;
use Doctrine\ORM\Mapping\Driver\SimplifiedXmlDriver;
use Doctrine\ORM\Mapping\NamingStrategy;
use Doctrine\ORM\Mapping\UnderscoreNamingStrategy;
use Doctrine\Persistence\Mapping\Driver\MappingDriver;
use Doctrine\Persistence\Mapping\RuntimeReflectionService;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\Attributes\Test;
use PHPUnit\Framework\TestCase;
use UnitEnum;

use function dirname;
use function sort;

use const CASE_LOWER;

/**
 * REQ-ARCH-001 rule 2 (`doctrine.mapping_type: xml`): the XML mapping (generated by .scripts/generate-doctrine-xml.php)
 * describes exactly the same metadata as the attributes, under any naming strategy.
 */
final class XmlMappingParityTest extends TestCase
{
    /**
     * @return iterable<string, array{NamingStrategy}>
     */
    public static function namingStrategies(): iterable
    {
        yield 'default' => [new DefaultNamingStrategy()];
        yield 'underscore' => [new UnderscoreNamingStrategy(CASE_LOWER, true)];
    }

    #[Test]
    #[DataProvider('namingStrategies')]
    public function xmlAndAttributesGiveTheSameMetadata(NamingStrategy $naming): void
    {
        $root       = dirname(__DIR__, 2);
        $attributes = new AttributeDriver([$root . '/src/Entity']);
        $xml        = new SimplifiedXmlDriver([$root . '/src/Resources/config/doctrine-xml' => 'Nowo\\BlogKitBundle\\Entity'], SimplifiedXmlDriver::DEFAULT_FILE_EXTENSION, true);

        $classes    = $attributes->getAllClassNames();
        $xmlClasses = $xml->getAllClassNames();
        sort($classes);
        sort($xmlClasses);
        self::assertSame($classes, $xmlClasses, 'one XML file per entity');

        foreach ($classes as $class) {
            self::assertEquals($this->describe($attributes, $class, $naming), $this->describe($xml, $class, $naming), $class);
        }
    }

    /**
     * @param class-string $class
     *
     * @return array<string, mixed>
     */
    private function describe(MappingDriver $driver, string $class, NamingStrategy $naming): array
    {
        $metadata = new ClassMetadata($class, $naming);
        $metadata->initializeReflection(new RuntimeReflectionService());
        $driver->loadMetadataForClass($class, $metadata);

        $fields = [];
        foreach ($metadata->fieldMappings as $name => $mapping) {
            $fields[$name] = (array) $mapping;
        }

        $associations = [];
        foreach ($metadata->associationMappings as $name => $mapping) {
            $array = $mapping->toArray();
            // The attributes may use the SortDirection enum, XML the strings: the same order for the ORM.
            foreach ($array['orderBy'] ?? [] as $field => $direction) {
                $array['orderBy'][$field] = $direction instanceof UnitEnum ? ($direction->name === 'Descending' ? 'DESC' : 'ASC') : $direction;
            }

            $associations[$name] = $array;
        }

        return [
            'table'              => $metadata->table,
            'repository'         => $metadata->customRepositoryClassName,
            'identifier'         => $metadata->identifier,
            'generator'          => $metadata->generatorType,
            'fields'             => $fields,
            'associations'       => $associations,
            'lifecycle'          => $metadata->lifecycleCallbacks,
            'isMappedSuperclass' => $metadata->isMappedSuperclass,
        ];
    }
}
