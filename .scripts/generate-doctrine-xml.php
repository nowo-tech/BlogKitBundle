<?php

declare(strict_types=1);

/*
 * Generates src/Resources/config/doctrine-xml/*.orm.xml from the ORM attributes of src/Entity (REQ-ARCH-001 rule 2,
 * `doctrine.mapping_type: xml`). Run it after changing an entity attribute; XmlMappingParityTest fails until then.
 *
 *   php .scripts/generate-doctrine-xml.php
 *
 * Names the attributes leave to the naming strategy (columns, join columns) stay implicit in the XML too: the metadata
 * is read with a naming strategy that marks every derived name, and marked names are not written.
 */

use Doctrine\ORM\Mapping\ClassMetadata;
use Doctrine\ORM\Mapping\Driver\AttributeDriver;
use Doctrine\ORM\Mapping\JoinColumnMapping;
use Doctrine\ORM\Mapping\ManyToManyOwningSideMapping;
use Doctrine\ORM\Mapping\NamingStrategy;
use Doctrine\ORM\Mapping\ToOneOwningSideMapping;
use Doctrine\ORM\ORMSetup;
use Doctrine\DBAL\DriverManager;
use Doctrine\ORM\EntityManager;

require dirname(__DIR__) . '/vendor/autoload.php';

const AUTO = '__auto__';

final class MarkingNamingStrategy implements NamingStrategy
{
    public function classToTableName(string $className): string
    {
        return AUTO;
    }

    public function propertyToColumnName(string $propertyName, string $className): string
    {
        return AUTO . $propertyName;
    }

    public function embeddedFieldToColumnName(string $propertyName, string $embeddedColumnName, string $className, string $embeddedClassName): string
    {
        return AUTO . $propertyName;
    }

    public function referenceColumnName(): string
    {
        return 'id';
    }

    public function joinColumnName(string $propertyName, string $className): string
    {
        return AUTO . $propertyName;
    }

    public function joinTableName(string $sourceEntity, string $targetEntity, string $propertyName): string
    {
        return AUTO;
    }

    public function joinKeyColumnName(string $entityName, ?string $referencedColumnName): string
    {
        return AUTO . $entityName;
    }
}

$root   = dirname(__DIR__);
$target = $root . '/src/Resources/config/doctrine-xml';
@mkdir($target, 0o775, true);

$config = ORMSetup::createAttributeMetadataConfiguration([$root . '/src/Entity'], true);
$config->setNamingStrategy(new MarkingNamingStrategy());
$config->enableNativeLazyObjects(true);
$connection = DriverManager::getConnection(['driver' => 'pdo_sqlite', 'memory' => true], $config);
$manager    = new EntityManager($connection, $config);
/** @var AttributeDriver $driver */
$driver = $config->getMetadataDriverImpl();

$auto = static fn (?string $name): bool => $name === null || str_starts_with($name, AUTO);

foreach ($driver->getAllClassNames() as $class) {
    $metadata = new ClassMetadata($class, new MarkingNamingStrategy());
    $metadata->initializeReflection(new Doctrine\Persistence\Mapping\RuntimeReflectionService());
    $driver->loadMetadataForClass($class, $metadata);

    $xml = new XMLWriter();
    $xml->openMemory();
    $xml->setIndent(true);
    $xml->setIndentString('    ');
    $xml->startDocument('1.0', 'UTF-8');
    $xml->writeComment(' Generated by .scripts/generate-doctrine-xml.php from the ORM attributes of ' . $class . '; do not edit. ');
    $xml->startElement('doctrine-mapping');
    $xml->writeAttribute('xmlns', 'http://doctrine-project.org/schemas/orm/doctrine-mapping');
    $xml->writeAttribute('xmlns:xsi', 'http://www.w3.org/2001/XMLSchema-instance');
    $xml->writeAttribute('xsi:schemaLocation', 'http://doctrine-project.org/schemas/orm/doctrine-mapping https://www.doctrine-project.org/schemas/orm/doctrine-mapping.xsd');

    $xml->startElement($metadata->isMappedSuperclass ? 'mapped-superclass' : 'entity');
    $xml->writeAttribute('name', $class);
    if (!$auto($metadata->table['name'] ?? null)) {
        $xml->writeAttribute('table', $metadata->table['name']);
    }
    if ($metadata->customRepositoryClassName !== null) {
        $xml->writeAttribute('repository-class', $metadata->customRepositoryClassName);
    }

    foreach (['indexes' => 'index', 'uniqueConstraints' => 'unique-constraint'] as $key => $element) {
        if (($metadata->table[$key] ?? []) === []) {
            continue;
        }
        $xml->startElement($element === 'index' ? 'indexes' : 'unique-constraints');
        foreach ($metadata->table[$key] as $name => $index) {
            $xml->startElement($element);
            $xml->writeAttribute('name', (string) $name);
            $xml->writeAttribute('columns', implode(',', $index['columns']));
            $xml->endElement();
        }
        $xml->endElement();
    }

    foreach ($metadata->fieldMappings as $field => $mapping) {
        $isId = in_array($field, $metadata->identifier, true);
        $xml->startElement($isId ? 'id' : 'field');
        $xml->writeAttribute('name', $field);
        $xml->writeAttribute('type', $mapping->type);
        if (!$auto($mapping->columnName)) {
            $xml->writeAttribute('column', $mapping->columnName);
        }
        if ($mapping->length !== null) {
            $xml->writeAttribute('length', (string) $mapping->length);
        }
        if ($mapping->unique === true) {
            $xml->writeAttribute('unique', 'true');
        }
        if ($mapping->nullable === true && !$isId) {
            $xml->writeAttribute('nullable', 'true');
        }
        if ($mapping->enumType !== null) {
            $xml->writeAttribute('enum-type', $mapping->enumType);
        }
        if ($isId) {
            $xml->startElement('generator');
            $xml->writeAttribute('strategy', match ($metadata->generatorType) {
                ClassMetadata::GENERATOR_TYPE_AUTO     => 'AUTO',
                ClassMetadata::GENERATOR_TYPE_IDENTITY => 'IDENTITY',
                ClassMetadata::GENERATOR_TYPE_SEQUENCE => 'SEQUENCE',
                default                                => 'NONE',
            });
            $xml->endElement();
        }
        if (($mapping->options ?? []) !== []) {
            $xml->startElement('options');
            foreach ($mapping->options as $name => $value) {
                $xml->startElement('option');
                $xml->writeAttribute('name', (string) $name);
                $xml->text(is_bool($value) ? ($value ? 'true' : 'false') : (string) $value);
                $xml->endElement();
            }
            $xml->endElement();
        }
        $xml->endElement();
    }

    foreach ($metadata->associationMappings as $field => $mapping) {
        $element = match (true) {
            $mapping->isManyToOne()  => 'many-to-one',
            $mapping->isOneToMany()  => 'one-to-many',
            $mapping->isManyToMany() => 'many-to-many',
            default                  => 'one-to-one',
        };
        $xml->startElement($element);
        $xml->writeAttribute('field', $field);
        $xml->writeAttribute('target-entity', $mapping->targetEntity);
        if ($mapping->isOwningSide() && $mapping->inversedBy !== null) {
            $xml->writeAttribute('inversed-by', $mapping->inversedBy);
        }
        if (!$mapping->isOwningSide()) {
            $xml->writeAttribute('mapped-by', $mapping->mappedBy);
        }
        if ($mapping->orphanRemoval) {
            $xml->writeAttribute('orphan-removal', 'true');
        }
        if ($mapping->fetch !== ClassMetadata::FETCH_LAZY) {
            $xml->writeAttribute('fetch', $mapping->fetch === ClassMetadata::FETCH_EAGER ? 'EAGER' : 'EXTRA_LAZY');
        }
        $cascade = array_values(array_filter(['persist', 'remove', 'refresh', 'detach'], static fn (string $op): bool => in_array($op, $mapping->cascade, true)));
        if ($cascade !== []) {
            $xml->startElement('cascade');
            foreach ($cascade as $op) {
                $xml->writeElement('cascade-' . $op);
            }
            $xml->endElement();
        }
        if ($mapping instanceof ToOneOwningSideMapping) {
            $xml->startElement('join-columns');
            foreach ($mapping->joinColumns as $join) {
                writeJoinColumn($xml, $join, $auto);
            }
            $xml->endElement();
        }
        if ($mapping instanceof ManyToManyOwningSideMapping) {
            $xml->startElement('join-table');
            if (!$auto($mapping->joinTable->name)) {
                $xml->writeAttribute('name', $mapping->joinTable->name);
            }
            $xml->startElement('join-columns');
            foreach ($mapping->joinTable->joinColumns as $join) {
                writeJoinColumn($xml, $join, $auto);
            }
            $xml->endElement();
            $xml->startElement('inverse-join-columns');
            foreach ($mapping->joinTable->inverseJoinColumns as $join) {
                writeJoinColumn($xml, $join, $auto);
            }
            $xml->endElement();
            $xml->endElement();
        }
        if (isset($mapping->orderBy) && $mapping->orderBy !== []) {
            $xml->startElement('order-by');
            foreach ($mapping->orderBy as $orderField => $direction) {
                $xml->startElement('order-by-field');
                $xml->writeAttribute('name', $orderField);
                $xml->writeAttribute('direction', $direction instanceof UnitEnum ? ($direction->name === 'Descending' ? 'DESC' : 'ASC') : (string) $direction);
                $xml->endElement();
            }
            $xml->endElement();
        }
        $xml->endElement();
    }

    $xml->endElement();
    $xml->endElement();
    $xml->endDocument();

    $file = $target . '/' . substr($class, strrpos($class, '\\') + 1) . '.orm.xml';
    file_put_contents($file, $xml->outputMemory());
    echo 'wrote ', substr($file, strlen($root) + 1), "\n";
}

/**
 * @param Closure(?string): bool $auto
 */
function writeJoinColumn(XMLWriter $xml, JoinColumnMapping $join, Closure $auto): void
{
    $xml->startElement('join-column');
    if (!$auto($join->name)) {
        $xml->writeAttribute('name', $join->name);
    }
    if ($join->referencedColumnName !== 'id') {
        $xml->writeAttribute('referenced-column-name', $join->referencedColumnName);
    }
    if ($join->nullable === false) {
        $xml->writeAttribute('nullable', 'false');
    }
    if ($join->onDelete !== null) {
        $xml->writeAttribute('on-delete', $join->onDelete);
    }
    $xml->endElement();
}
